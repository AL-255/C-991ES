/* Readable high-level translation of the special-result table matcher.
 * GPL-3.0-or-later. The numeric sine/cosine/tangent cores are separate work. */
#include "fx_trig.h"
#include <stddef.h>

typedef struct { fx_number decimal, exact; } special_value;
/* These are numeric objects, not output strings. Sine/cosine share five
 * positive magnitudes; tangent has four. Their signs are restored after
 * selecting the replacement. Source data:29F6..2AA9 in the original ROM. */
